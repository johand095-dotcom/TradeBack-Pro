-- ELT PDI LIVE: add "COF Done" as step 35 (Phase 4 / Sales Admin).
-- Execute in LIVE Supabase SQL Editor only after a backup and a quiet maintenance window.
-- Transactional; preserves existing case-step IDs, audit fields, attachments and history.
-- Existing steps 35+ shift to 36+; existing case current_step pointers shift accordingly.
-- Already-progressed cases have COF marked as NOT retrospectively verified: Pending,
-- except when the case has passed the original step 35, where a review is required.
BEGIN;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM public.pdi_step_templates
    WHERE step_no=35 AND phase_no=4 AND activity ILIKE '%inspected by the Sales Admin%'
  ) THEN
    RAISE EXCEPTION 'Expected original Step 35 not found (or migration already run). No changes made.';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.pdi_step_templates WHERE step_no=36 AND phase_no=4 AND phase_name IS NOT NULL) THEN
    RAISE EXCEPTION 'Expected Phase 4 template with a phase name not found. No changes made.';
  END IF;
  IF EXISTS (SELECT 1 FROM public.pdi_step_templates WHERE step_no >= 1000)
     OR EXISTS (SELECT 1 FROM public.pdi_case_steps WHERE step_no >= 1000) THEN
    RAISE EXCEPTION 'Temporary step-number range 1000+ is occupied. No changes made.';
  END IF;
  IF EXISTS (
    SELECT 1 FROM public.pdi_cases WHERE current_step >= 1000
  ) THEN
    RAISE EXCEPTION 'Unexpected current_step >=1000. No changes made.';
  END IF;
END $$;

-- Shift through a temporary range to avoid UNIQUE(pdi_case_id,step_no) collisions.
UPDATE public.pdi_case_steps SET step_no=step_no+1000 WHERE step_no>=35;
UPDATE public.pdi_step_templates SET step_no=step_no+1000 WHERE step_no>=35;
UPDATE public.pdi_case_steps SET step_no=step_no-999 WHERE step_no>=1035;
UPDATE public.pdi_step_templates SET step_no=step_no-999 WHERE step_no>=1035;

-- Keep current-step pointers attached to their original activities.
UPDATE public.pdi_cases SET current_step=current_step+1 WHERE current_step>=35;

INSERT INTO public.pdi_step_templates(step_no,phase_no,phase_name,activity,responsible_role,target_hours)
SELECT 35,4,phase_name,'COF Done','Sales Admin',2
FROM public.pdi_step_templates WHERE step_no=36 AND phase_no=4;

-- Add a real pending step to all cases with existing workflow rows.
-- The identity column id is generated by PostgreSQL automatically.
-- Do not fabricate COF completion for previously processed vehicles.
INSERT INTO public.pdi_case_steps
  (pdi_case_id,step_no,phase_no,activity,responsible_role,step_status,comments)
SELECT DISTINCT s.pdi_case_id,35,4,'COF Done','Sales Admin','Pending',
  CASE WHEN c.current_step>35
    THEN 'COF introduced after vehicle had progressed; Sales Admin must verify status.'
    ELSE NULL END
FROM public.pdi_case_steps s
JOIN public.pdi_cases c ON c.id=s.pdi_case_id
WHERE NOT EXISTS (
  SELECT 1 FROM public.pdi_case_steps x
  WHERE x.pdi_case_id=s.pdi_case_id AND x.step_no=35
);

COMMIT;

