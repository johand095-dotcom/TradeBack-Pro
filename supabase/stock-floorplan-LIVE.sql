-- ELT Stock Management: LIVE migration. Execute in Supabase SQL Editor after review.
-- Adds floorplan metadata to the existing PDI record; VIN and receipt date stay canonical in PDI.
BEGIN;
ALTER TABLE public.pdi_cases
  ADD COLUMN IF NOT EXISTS tradeback_option text,
  ADD COLUMN IF NOT EXISTS floorplan_provider text,
  ADD COLUMN IF NOT EXISTS vehicle_range text;
CREATE TABLE IF NOT EXISTS public.stock_floorplan_settlements (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 pdi_case_id bigint NOT NULL UNIQUE REFERENCES public.pdi_cases(id) ON DELETE RESTRICT,
 settled_at timestamptz NOT NULL DEFAULT now(),
 settled_by uuid NOT NULL REFERENCES auth.users(id),
 document_path text NOT NULL,
 document_name text NOT NULL,
 remarks text,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE OR REPLACE FUNCTION public.stock_access_allowed()
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public AS $$
 SELECT EXISTS(
 SELECT 1 FROM public.user_profiles u
 WHERE u.user_id=auth.uid() AND u.is_active IS TRUE AND
 (u.is_admin IS TRUE OR 'sales admin'=ANY(ARRAY(SELECT lower(x) FROM unnest(COALESCE(u.roles,ARRAY[]::text[])) x))
 OR lower(u.email) IN ('marca@eltgroup.co.za','sp@eltgroup.co.za'))
 ) $$;
REVOKE ALL ON FUNCTION public.stock_access_allowed() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.stock_access_allowed() TO authenticated;
CREATE OR REPLACE FUNCTION public.stock_floorplan_days(p_provider text,p_range text)
RETURNS integer LANGUAGE sql IMMUTABLE AS $$
 SELECT CASE
 WHEN p_provider='FFS' AND p_range IN ('MCV','HCV') THEN 60
 WHEN p_provider='FFS' AND p_range='EHCV' THEN 90
 WHEN p_provider='Sinosure' AND p_range IN ('MCV','HCV') THEN 90
 WHEN p_provider='Sinosure' AND p_range='EHCV' THEN 120
 WHEN p_provider='Iveco' AND p_range IN ('MCV','HCV','EHCV') THEN 60
 ELSE NULL END $$;
ALTER TABLE public.stock_floorplan_settlements ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS stock_settlements_read ON public.stock_floorplan_settlements;
CREATE POLICY stock_settlements_read ON public.stock_floorplan_settlements FOR SELECT TO authenticated USING (public.stock_access_allowed());
-- Settlement records are written only through a privileged RPC, not direct client inserts.
CREATE OR REPLACE FUNCTION public.stock_mark_settled(p_case_id bigint,p_document_path text,p_document_name text,p_remarks text DEFAULT NULL)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE v_case public.pdi_cases%ROWTYPE;
BEGIN
 IF NOT public.stock_access_allowed() THEN RAISE EXCEPTION 'Stock Management access denied'; END IF;
 IF NULLIF(trim(p_document_path),'') IS NULL OR NULLIF(trim(p_document_name),'') IS NULL THEN
  RAISE EXCEPTION 'Settlement document required'; END IF;
 SELECT * INTO v_case FROM public.pdi_cases WHERE id=p_case_id FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'PDI vehicle not found'; END IF;
 IF v_case.received_at IS NULL OR v_case.floorplan_provider IS NULL OR v_case.vehicle_range IS NULL THEN
  RAISE EXCEPTION 'Received vehicle and floorplan classification required'; END IF;
 IF EXISTS(SELECT 1 FROM public.stock_floorplan_settlements WHERE pdi_case_id=p_case_id) THEN
  RAISE EXCEPTION 'Vehicle already settled'; END IF;
 INSERT INTO public.stock_floorplan_settlements(pdi_case_id,settled_by,document_path,document_name,remarks)
 VALUES(p_case_id,auth.uid(),p_document_path,p_document_name,p_remarks);
END $$;
REVOKE ALL ON FUNCTION public.stock_mark_settled(bigint,text,text,text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.stock_mark_settled(bigint,text,text,text) TO authenticated;
CREATE OR REPLACE FUNCTION public.stock_floorplan_register()
RETURNS TABLE(
 pdi_case_id bigint,vin text,stock_no text,make text,model text,received_at timestamptz,
 tradeback_option text,floorplan_provider text,vehicle_range text,
 days_allowed integer,due_date date,days_remaining integer,
 settled_at timestamptz,document_path text,document_name text,remarks text
) LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path=public,pg_temp AS $$
BEGIN
 IF NOT public.stock_access_allowed() THEN RAISE EXCEPTION 'Stock Management access denied'; END IF;
 RETURN QUERY
 SELECT p.id,p.vin,p.stock_no,p.make,p.model,p.received_at,
 p.tradeback_option,p.floorplan_provider,p.vehicle_range,
 public.stock_floorplan_days(p.floorplan_provider,p.vehicle_range),
 ((p.received_at AT TIME ZONE 'Africa/Johannesburg')::date+
 public.stock_floorplan_days(p.floorplan_provider,p.vehicle_range))::date,
 ((p.received_at AT TIME ZONE 'Africa/Johannesburg')::date+
 public.stock_floorplan_days(p.floorplan_provider,p.vehicle_range))- (now() AT TIME ZONE 'Africa/Johannesburg')::date,
 s.settled_at,s.document_path,s.document_name,s.remarks
 FROM public.pdi_cases p LEFT JOIN public.stock_floorplan_settlements s ON s.pdi_case_id=p.id
 WHERE p.received_at IS NOT NULL AND p.floorplan_provider IS NOT NULL AND p.vehicle_range IS NOT NULL
 ORDER BY s.settled_at NULLS FIRST,p.received_at DESC;
END $$;
REVOKE ALL ON FUNCTION public.stock_floorplan_register() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.stock_floorplan_register() TO authenticated;
INSERT INTO storage.buckets(id,name,public,file_size_limit,allowed_mime_types)
VALUES('stock-settlement-docs','stock-settlement-docs',false,15728640,ARRAY['application/pdf','image/jpeg','image/png'])
ON CONFLICT (id) DO NOTHING;
DROP POLICY IF EXISTS stock_docs_insert ON storage.objects;
CREATE POLICY stock_docs_insert ON storage.objects FOR INSERT TO authenticated
WITH CHECK (bucket_id='stock-settlement-docs' AND public.stock_access_allowed() AND (storage.foldername(name))[1]=auth.uid()::text);
DROP POLICY IF EXISTS stock_docs_read ON storage.objects;
CREATE POLICY stock_docs_read ON storage.objects FOR SELECT TO authenticated
USING (bucket_id='stock-settlement-docs' AND public.stock_access_allowed());
COMMIT;
